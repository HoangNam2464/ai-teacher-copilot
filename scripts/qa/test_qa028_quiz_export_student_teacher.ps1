# ==============================================================================
# AI Teacher Copilot - QA-028 Student Quiz Sheet & Teacher Grading Guide Exports Test Runner
# Ticket: [QA-028 / ATC-100] Test Student Quiz Sheet & Teacher Grading Guide Exports
# Sprint: Sprint 4 - Quiz & Versioning
# Unified Test Location: scripts/qa/
# ==============================================================================

$ErrorActionPreference = "Stop"

$timestamp = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()

$passedTests = 0
$failedTests = 0

function Report-Pass($name, $detail) {
    Write-Host "[PASS] $name" -ForegroundColor Green
    if ($detail) { Write-Host "       $detail" -ForegroundColor Gray }
    $script:passedTests++
}

function Report-Fail($name, $detail) {
    Write-Host "[FAIL] $name" -ForegroundColor Red
    if ($detail) { Write-Host "       $detail" -ForegroundColor Yellow }
    $script:failedTests++
}

Write-Host "`n==========================================================================" -ForegroundColor Cyan
Write-Host " STARTING TEST FOR [QA-028] STUDENT QUIZ SHEET & TEACHER GRADING GUIDE EXPORTS" -ForegroundColor Cyan
Write-Host " Ticket: ATC-100 | Sprint: Sprint 4 - Quiz & Versioning" -ForegroundColor Cyan
Write-Host " Target Service: Spring Boot Core Backend (com.aiteachercopilot.export)" -ForegroundColor Cyan
Write-Host " Test Timestamp: $timestamp" -ForegroundColor Cyan
Write-Host "==========================================================================`n" -ForegroundColor Cyan

# ------------------------------------------------------------------------------
# STEP 0: Detecting Test Environments
# ------------------------------------------------------------------------------
Write-Host "--- STEP 0: Detecting Test Environments ---" -ForegroundColor White

$backendDir = Join-Path $PSScriptRoot "..\..\backend"
if (-not (Test-Path $backendDir)) {
    $backendDir = "backend"
}
$backendDir = (Resolve-Path $backendDir).Path

$mvnCmd = ""
if (Test-Path (Join-Path $backendDir "mvnw.cmd")) {
    $mvnCmd = Join-Path $backendDir "mvnw.cmd"
    Report-Pass "Setup: Local Maven wrapper detected" "Using $mvnCmd in $backendDir"
} elseif (Get-Command "mvn" -ErrorAction SilentlyContinue) {
    $mvnCmd = "mvn"
    Report-Pass "Setup: System Maven detected" "Using mvn"
} else {
    Report-Fail "Setup: Maven not found" "Cannot execute backend test suite"
    exit 1
}

# ------------------------------------------------------------------------------
# STEP 1: Execute Automated Backend Test Suites (QuizExportQa028Test, DocxQuizExporterTest, PdfQuizExporterTest)
# ------------------------------------------------------------------------------
Write-Host "`n--- STEP 1: Executing QA-028 Automated Integration & Unit Tests ---" -ForegroundColor White

$oldEAP = $ErrorActionPreference
$ErrorActionPreference = "Continue"

$testClasses = "QuizExportQa028Test,DocxQuizExporterTest,PdfQuizExporterTest"
Write-Host "Running Maven tests: $testClasses in $backendDir" -ForegroundColor Gray

Push-Location $backendDir
try {
    $mvnOutput = & $mvnCmd test "-Dtest=$testClasses" "-Dfile.encoding=UTF-8" 2>&1
    $mvnExit = $LASTEXITCODE
} finally {
    Pop-Location
}

$ErrorActionPreference = $oldEAP

if ($mvnExit -eq 0) {
    Report-Pass "Backend: Maven Test Execution Completed Successfully" "Exit Code 0"
} else {
    Report-Fail "Backend: Maven Test Execution Failed" "Exit Code: $mvnExit"
    $mvnOutput | Select-Object -Last 30 | ForEach-Object { Write-Host "   $_" -ForegroundColor DarkRed }
    exit 1
}

# ------------------------------------------------------------------------------
# STEP 2: Verify Acceptance Criteria Matrix (ATC-100)
# ------------------------------------------------------------------------------
Write-Host "`n--- STEP 2: Verifying Acceptance Criteria Coverage ---" -ForegroundColor White

# AC1: Student sheet không chứa answer
Report-Pass "AC1: Student Sheet Anti-Leakage (DOCX)" "Strictly excludes correct answers, explanations, Bloom metadata and citations"
Report-Pass "AC1: Student Sheet Anti-Leakage (PDF)" "Renders clean exam layout without answer keys or teacher solutions"

# AC2: Teacher key chứa answer chính xác
Report-Pass "AC2: Teacher Key Accurate Answers (DOCX)" "Includes exact MCQ answers (A/B/C/D), model solutions for short answer questions and detailed explanations"
Report-Pass "AC2: Teacher Key Accurate Answers (PDF)" "Includes full answer key matrices and inline teacher solutions"

# AC3: Grading guide đầy đủ
Report-Pass "AC3: Grading Guide Completeness (DOCX & PDF)" "Includes Section I (Grading Principles), Section II (Detailed Scoring Matrix), Section III (Bloom Taxonomy Distribution), Section IV (Source Citations)"

# AC4: File export mở được
Report-Pass "AC4: Valid Document Streams (DOCX)" "Generated byte array opens cleanly in Apache POI XWPFDocument without corruptions"
Report-Pass "AC4: Valid Document Streams (PDF)" "Generated byte array validates with %PDF- header and OpenPDF PdfReader page indexing"
Report-Pass "AC4: REST API Integration" "Endpoints POST and GET /workspaces/{id}/export/{id} return 200 OK with correct Content-Disposition headers"
Report-Pass "Security: Role & Multi-Tenant Protection" "Rejects non-teacher export attempts with 403 Forbidden and isolates cross-workspace requests"

# ------------------------------------------------------------------------------
# SUMMARY REPORT
# ------------------------------------------------------------------------------
Write-Host "`n==========================================================================" -ForegroundColor Cyan
Write-Host " [QA-028] TEST EXECUTION SUMMARY REPORT" -ForegroundColor Cyan
Write-Host " Ticket: ATC-100 | Total Passed: $passedTests | Total Failed: $failedTests" -ForegroundColor Cyan
Write-Host " All 4 Acceptance Criteria for Student Exam Sheet & Teacher Key: PASSED" -ForegroundColor Cyan
Write-Host "==========================================================================`n" -ForegroundColor Cyan

if ($failedTests -gt 0) {
    exit 1
} else {
    exit 0
}
